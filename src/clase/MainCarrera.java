    private void bntStartActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bntStartActionPerformed

        nombre1 = JOptionPane.showInputDialog(this, "Ingrese el nombre del Caballo 1");
        nombre2 = JOptionPane.showInputDialog(this, "Ingrese el nombre del Caballo 2");
        nombre3 = JOptionPane.showInputDialog(this, "Ingrese el nombre del Caballo 3");

        if (nombre1 == null || nombre2 == null || nombre3 == null
                || nombre1.trim().equals("") || nombre2.trim().equals("") || nombre3.trim().equals("")) {
            JOptionPane.showMessageDialog(this, "Debe ingresar los 3 nombres");
            return;
        }

        terminado = 0;
        int inicio = 10;
        int meta = lblMeta.getX() - lblCaballo1.getWidth();

        lblCaballo1.setText(nombre1);
        lblCaballo2.setText(nombre2);
        lblCaballo3.setText(nombre3);

        lblCaballo1.setLocation(10, lblCaballo1.getY());
        lblCaballo2.setLocation(10, lblCaballo2.getY());
        lblCaballo3.setLocation(10, lblCaballo3.getY());

        lblCaballo1.setHorizontalTextPosition(lblCaballo1.CENTER);
        lblCaballo1.setVerticalTextPosition(lblCaballo1.TOP);
        lblCaballo2.setHorizontalTextPosition(lblCaballo2.CENTER);
        lblCaballo2.setVerticalTextPosition(lblCaballo2.TOP);
        lblCaballo3.setHorizontalTextPosition(lblCaballo3.CENTER);
        lblCaballo3.setVerticalTextPosition(lblCaballo3.TOP);

        lblCaballo1.setText(nombre1);
        lblCaballo2.setText(nombre2);
        lblCaballo3.setText(nombre3);

        lblCaballo1.setLocation(inicio, lblCaballo1.getY());
        lblCaballo2.setLocation(inicio, lblCaballo2.getY());
        lblCaballo3.setLocation(inicio, lblCaballo3.getY());

        caballo1 = new CaballosHilo(nombre1, lblCaballo1, pgb1, inicio, this, meta);
        caballo2 = new CaballosHilo(nombre2, lblCaballo2, pgb2, inicio, this, meta);
        caballo3 = new CaballosHilo(nombre3, lblCaballo3, pgb3, inicio, this, meta);

        caballo1.start();
        caballo2.start();
        caballo3.start();

    }

    public synchronized void caballoTermino() {
        terminado++;

        if (terminado == 3) {
            long menor = caballo1.getTime();
            if (caballo2.getTime() < menor) {
                menor = caballo2.getTime();
            }
            if (caballo3.getTime() < menor) {
                menor = caballo3.getTime();
            }

            int cuantos = 0;
            String ganadores = "";
            if (caballo1.getTime() == menor) {
                ganadores = ganadores + caballo1.getNombre() + " ";
                cuantos++;
            }
            if (caballo2.getTime() == menor) {
                ganadores = ganadores + caballo2.getNombre() + " ";
                cuantos++;
            }
            if (caballo3.getTime() == menor) {
                ganadores = ganadores + caballo3.getNombre() + " ";
                cuantos++;
            }

            String texto = "";
            if (cuantos == 1) {
                texto = "GANADOR:\n" + ganadores + "\n";
            } else {
                texto = "EMPATE entre:\n" + ganadores + "\n";
            }

            texto = texto + "\nTIEMPOS:\n";
            texto = texto + caballo1.getNombre() + ": " + caballo1.getTime() + " ms\n";
            texto = texto + caballo2.getNombre() + ": " + caballo2.getTime() + " ms\n";
            texto = texto + caballo3.getNombre() + ": " + caballo3.getTime() + " ms\n";

            JOptionPane.showMessageDialog(this, texto, "Resultado de la Carrera", JOptionPane.INFORMATION_MESSAGE);

        }


    }//GEN-LAST:event_bntStartActionPerformed

